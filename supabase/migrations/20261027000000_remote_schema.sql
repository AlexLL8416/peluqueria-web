create type public.tipo_servicio as enum ('Corte de pelo', 'Peinado y Styling', 'Color y Mechas');

create table public.citas (
    id uuid primary key default gen_random_uuid(),
    created_at timestamptz default now(),
    fecha_hora timestamptz not null,
    duracion_minutos integer default 30,
    tipo public.tipo_servicio not null,
    google_event_id text,
    estado text default 'disponible'
        constraint citas_estado_check check (estado = any (array['disponible', 'reservada', 'cancelada'])),
    nombre_cliente text,
    telefono text
);

create table public.baneados (
    id bigint generated by default as identity primary key,
    created_at timestamptz not null default timezone('utc', now()),
    telefono text not null unique
);

alter table public.citas enable row level security;
alter table public.baneados enable row level security;

create policy "Admin total" on public.citas
    for all to authenticated using (true) with check (true);
create policy "Lectura publica" on public.citas
    for select to anon using (true);
create policy "Clientes actualizar estado" on public.citas
    for update to anon
    using (estado = any (array['disponible', 'reservada']))
    with check (
        (estado = 'reservada' and nombre_cliente is not null and telefono is not null)
        or estado = 'cancelada' or estado = 'disponible'
    );

create policy "Permitir lectura publica de baneados" on public.baneados
    for select to public using (true);
create policy "Permitir insertar solo a admins" on public.baneados
    for insert to authenticated with check (true);
create policy "Permitir borrar solo a admins" on public.baneados
    for delete to authenticated using (true);

-- Event trigger que activa RLS en tablas nuevas de public.
create or replace function public.rls_auto_enable()
 returns event_trigger
 language plpgsql
 security definer
 set search_path to 'pg_catalog'
as $function$
declare
  cmd record;
begin
  for cmd in
    select *
    from pg_event_trigger_ddl_commands()
    where command_tag in ('CREATE TABLE', 'CREATE TABLE AS', 'SELECT INTO')
      and object_type in ('table','partitioned table')
  loop
     if cmd.schema_name is not null and cmd.schema_name in ('public') and cmd.schema_name not in ('pg_catalog','information_schema') and cmd.schema_name not like 'pg_toast%' and cmd.schema_name not like 'pg_temp%' then
      begin
        execute format('alter table if exists %s enable row level security', cmd.object_identity);
        raise log 'rls_auto_enable: enabled RLS on %', cmd.object_identity;
      exception
        when others then
          raise log 'rls_auto_enable: failed to enable RLS on %', cmd.object_identity;
      end;
     else
        raise log 'rls_auto_enable: skip % (either system schema or not in enforced list: %.)', cmd.object_identity, cmd.schema_name;
     end if;
  end loop;
end;
$function$;

create event trigger ensure_rls on ddl_command_end
    when tag in ('CREATE TABLE', 'CREATE TABLE AS', 'SELECT INTO')
    execute function public.rls_auto_enable();
